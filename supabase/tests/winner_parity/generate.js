// Generates a pgTAP test proving that the database's private.ttt_winner(board)
// agrees with getWinner(board) in src/game.js on EVERY possible board:
// 3^9 = 19,683 boards (each square ".", "X" or "O"), including boards that
// can't happen in a real game.
//
// Usage (from the repository root):
//   node supabase/tests/winner_parity/generate.js > supabase/tests/database/winner_parity.test.sql
//   supabase test db
//
// How it works: board number i (0..19682) is written in base 3, one digit per
// square (0 = ".", 1 = "X", 2 = "O", square 0 = lowest digit). JavaScript
// computes the expected winner of every board and packs them into one
// 19,683-character string ("X", "O", or "." for no winner). The SQL builds the
// same boards from the same numbers and counts disagreements, which must be 0.

const Game = require("../../../src/game.js");

const BOARD_COUNT = 3 ** 9;
const SYMBOLS = ["", "X", "O"];

function boardFromNumber(n) {
  const board = [];
  for (let square = 0; square < 9; square++) {
    board.push(SYMBOLS[Math.floor(n / 3 ** square) % 3]);
  }
  return board;
}

// The board as the database stores it ("." for empty).
function boardString(n) {
  return boardFromNumber(n).map((v) => v || ".").join("");
}

// A few board numbers used to check that SQL and JS number boards alike.
const SAMPLES = [0, 1, 2, 3, 4, 13, 9841, BOARD_COUNT - 1];

let expected = "";
for (let n = 0; n < BOARD_COUNT; n++) {
  expected += Game.getWinner(boardFromNumber(n)) || ".";
}

const sql = `-- GENERATED by supabase/tests/winner_parity/generate.js - do not edit by hand.
-- Checks private.ttt_winner against src/game.js getWinner on all ${BOARD_COUNT} boards.
begin;
create extension if not exists pgtap with schema extensions;
select plan(2);

with boards as (
  select n,
         (select string_agg(substr('.XO', ((n / (3 ^ square)::integer) % 3) + 1, 1), '' order by square)
          from generate_series(0, 8) as square) as board
  from generate_series(0, ${BOARD_COUNT - 1}) as n
)
select is(
  (select count(*) from boards
   where coalesce(private.ttt_winner(board), '.')
         <> substr('${expected}', n + 1, 1)),
  0::bigint,
  'ttt_winner agrees with src/game.js getWinner on all ${BOARD_COUNT} boards'
);

-- The SQL must number the boards exactly like the JavaScript above, or the
-- comparison would line up the wrong boards. Spot-check a few.
select results_eq(
  $$ select n,
            (select string_agg(substr('.XO', ((n / (3 ^ square)::integer) % 3) + 1, 1), '' order by square)
             from generate_series(0, 8) as square)
     from generate_series(0, ${BOARD_COUNT - 1}) as n
     where n in (${SAMPLES.join(", ")})
     order by n $$,
  $$ values ${SAMPLES.map((n) => `(${n}, '${boardString(n)}')`).join(", ")} $$,
  'SQL numbers the boards the same way as the generator'
);

select * from finish();
rollback;
`;

process.stdout.write(sql);
